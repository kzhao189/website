"""Local editor for the site.

    python admin/server.py

Serves the site at http://localhost:5174/ and the editor at
http://localhost:5174/admin/. Saving in the editor writes content/posts.json
(the source of truth) and regenerates projects.js and site.css, which the
site loads.
Draft posts are saved to content/drafts.json instead, which git ignores, and
media only drafts use is listed in media/.gitignore, so drafts stay local.
Uploaded images and videos are stored in media/.

Standard library only; listens on localhost only.
"""

import json
import os
import re
import sys
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlparse

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content" / "posts.json"
DRAFTS = ROOT / "content" / "drafts.json"  # git-ignored: drafts stay on this machine
OUTPUT = ROOT / "projects.js"
SITE_CSS = ROOT / "site.css"
MEDIA = ROOT / "media"
PORT = int(os.environ.get("PORT", 5174))

MEDIA_TYPES = {
    ".jpg", ".jpeg", ".png", ".gif", ".webp", ".avif", ".svg",
    ".mp4", ".webm", ".mov", ".m4v",
}


def load_content():
    """Published posts from posts.json, merged with local drafts in their saved order."""
    with CONTENT.open(encoding="utf-8") as f:
        content = json.load(f)
    if DRAFTS.exists():
        with DRAFTS.open(encoding="utf-8") as f:
            drafts = json.load(f)
        posts = content["posts"] + drafts["posts"]
        rank = {slug: i for i, slug in enumerate(drafts.get("order", []))}
        posts.sort(key=lambda p: rank.get(p["slug"], len(rank)))
        content["posts"] = posts
    return content


def save_content(content):
    """Split drafts off into the git-ignored drafts.json; posts.json keeps the rest."""
    public = {**content, "posts": [p for p in content["posts"] if not p.get("draft")]}
    drafts = {
        "order": [p["slug"] for p in content["posts"]],
        "posts": [p for p in content["posts"] if p.get("draft")],
    }
    dump = lambda v: json.dumps(v, indent=2, ensure_ascii=False) + "\n"
    write_atomic(CONTENT, dump(public))
    write_atomic(DRAFTS, dump(drafts))


MEDIA_REF = re.compile(r"media/[^\s\"'()<>\\]+")


def media_refs(value):
    """Every media/ path mentioned anywhere in a chunk of content."""
    return set(MEDIA_REF.findall(json.dumps(value, ensure_ascii=False)))


def build_media_ignore(content):
    """media/.gitignore listing files only drafts use, so they stay local."""
    public = media_refs({**content, "posts": [p for p in content["posts"] if not p.get("draft")]})
    private = media_refs([p for p in content["posts"] if p.get("draft")]) - public
    names = sorted(ref.removeprefix("media/") for ref in private)
    return (
        "# Generated by admin/server.py: media used only by draft posts.\n"
        "# Publish the post in /admin/ to start tracking its files.\n"
        + "".join(f"/{name}\n" for name in names)
    )


def write_atomic(path, text):
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def build_site_data(content):
    """Turn editor content into projects.js (drafts are left out)."""
    tiers = content["tiers"]
    tier_ids = {t["id"] for t in tiers}
    posts = [
        {k: v for k, v in p.items() if k != "draft"}
        for p in content["posts"]
        if not p.get("draft") and p.get("tier") in tier_ids
    ]
    dump = lambda v: json.dumps(v, indent=2, ensure_ascii=False)
    return (
        "// Generated by admin/server.py from content/posts.json.\n"
        "// Don't edit by hand: run `python admin/server.py` and use /admin/.\n"
        f"window.TIERS = {dump(tiers)};\n\n"
        f"window.PROJECTS = {dump(posts)};\n\n"
        f"window.ABOUT = {dump(content.get('about'))};\n"
    )


# The cyanotype paper colour, as HSL. Matches SITE_DEFAULT in admin.js.
SITE_DEFAULT = {"hue": 218, "sat": 89, "light": 18}


HEX_COLOR = re.compile(r"#[0-9a-fA-F]{6}")


def build_site_css(content):
    """Turn the editor's background and heading colour settings into site.css."""
    site = {**SITE_DEFAULT, **content.get("site", {})}
    h, s, l = (round(float(site[k]), 1) for k in ("hue", "sat", "light"))
    # Unset, headings keep the body text colour (styles.css falls back to it).
    heading = f"  --heading: {site['heading']};\n" if site.get("heading") else ""
    return (
        "/* Generated by admin/server.py from content/posts.json.\n"
        "   Don't edit by hand: set the background in /admin/. */\n"
        ":root {\n"
        f"  --cyan: hsl({h:g} {s:g}% {l:g}%);\n"
        f"  --cyan-deep: hsl({h:g} {s:g}% {round(l * 0.75, 1):g}%);\n"
        f"{heading}"
        "}\n"
    )


def write_outputs(content):
    write_atomic(OUTPUT, build_site_data(content))
    write_atomic(SITE_CSS, build_site_css(content))
    MEDIA.mkdir(exist_ok=True)
    write_atomic(MEDIA / ".gitignore", build_media_ignore(content))


def validate(content):
    if not isinstance(content.get("tiers"), list) or not isinstance(content.get("posts"), list):
        return "content must have 'tiers' and 'posts' lists"
    slugs = set()
    for p in content["posts"]:
        slug = p.get("slug", "")
        if not re.fullmatch(r"[\w-]+", slug):
            return f"invalid slug {slug!r} (use letters, numbers, - and _)"
        if slug in slugs:
            return f"two posts share the slug {slug!r}"
        slugs.add(slug)
    about = content.get("about", {})
    if not isinstance(about, dict) or not isinstance(about.get("links", []), list):
        return "'about' must be an object with a 'links' list"
    site = content.get("site", {})
    if not isinstance(site, dict):
        return "'site' must be an object"
    for key, hi in (("hue", 360), ("sat", 100), ("light", 100)):
        v = site.get(key, SITE_DEFAULT[key])
        if isinstance(v, bool) or not isinstance(v, (int, float)) or not 0 <= v <= hi:
            return f"background {key} must be a number from 0 to {hi}"
    heading = site.get("heading")
    if heading is not None and not (isinstance(heading, str) and HEX_COLOR.fullmatch(heading)):
        return "heading colour must look like #rrggbb"
    return None


def safe_name(name):
    stem, ext = os.path.splitext(os.path.basename(name))
    stem = re.sub(r"[^\w-]+", "-", stem.lower()).strip("-_") or "file"
    return stem[:60], ext.lower()


class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT), **kwargs)

    def end_headers(self):
        # Always serve fresh files so saved edits show up on reload.
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def send_json(self, status, payload):
        body = json.dumps(payload).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        if urlparse(self.path).path == "/api/content":
            return self.send_json(200, load_content())
        if self.send_range():
            return
        super().do_GET()

    def send_range(self):
        """Answer `Range: bytes=a-b` so browsers can seek in videos."""
        m = re.fullmatch(r"bytes=(\d*)-(\d*)", self.headers.get("Range", ""))
        path = Path(self.translate_path(self.path))
        if not m or not path.is_file():
            return False
        size = path.stat().st_size
        if m[1]:
            start, end = int(m[1]), int(m[2]) if m[2] else size - 1
        elif m[2]:
            start, end = max(0, size - int(m[2])), size - 1
        else:
            return False
        end = min(end, size - 1)
        if start > end:
            self.send_response(416)
            self.send_header("Content-Range", f"bytes */{size}")
            self.end_headers()
            return True
        self.send_response(206)
        self.send_header("Content-Type", self.guess_type(str(path)))
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        self.send_header("Content-Length", str(end - start + 1))
        self.end_headers()
        with path.open("rb") as f:
            f.seek(start)
            remaining = end - start + 1
            while remaining > 0:
                chunk = f.read(min(remaining, 1 << 20))
                if not chunk:
                    break
                self.wfile.write(chunk)
                remaining -= len(chunk)
        return True

    def do_PUT(self):
        if urlparse(self.path).path != "/api/content":
            return self.send_json(404, {"error": "not found"})
        try:
            length = int(self.headers.get("Content-Length", 0))
            content = json.loads(self.rfile.read(length))
        except (ValueError, json.JSONDecodeError):
            return self.send_json(400, {"error": "invalid JSON"})
        error = validate(content)
        if error:
            return self.send_json(400, {"error": error})
        save_content(content)
        write_outputs(content)
        self.send_json(200, {"ok": True})

    def do_POST(self):
        url = urlparse(self.path)
        if url.path != "/api/upload":
            return self.send_json(404, {"error": "not found"})
        stem, ext = safe_name(parse_qs(url.query).get("name", ["file"])[0])
        if ext not in MEDIA_TYPES:
            return self.send_json(400, {"error": f"unsupported file type {ext or '(none)'}"})

        MEDIA.mkdir(exist_ok=True)
        target, n = MEDIA / f"{stem}{ext}", 1
        while target.exists():
            n += 1
            target = MEDIA / f"{stem}-{n}{ext}"

        remaining = int(self.headers.get("Content-Length", 0))
        with target.open("wb") as f:
            while remaining > 0:
                chunk = self.rfile.read(min(remaining, 1 << 20))
                if not chunk:
                    break
                f.write(chunk)
                remaining -= len(chunk)
        self.send_json(200, {"path": f"media/{target.name}"})


if __name__ == "__main__":
    # Regenerate on start so projects.js and site.css always match posts.json,
    # and move any drafts still in posts.json out into drafts.json.
    content = load_content()
    save_content(content)
    write_outputs(content)
    server = ThreadingHTTPServer(("127.0.0.1", PORT), Handler)
    print(f"Site:   http://localhost:{PORT}/")
    print(f"Editor: http://localhost:{PORT}/admin/")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        sys.exit(0)
